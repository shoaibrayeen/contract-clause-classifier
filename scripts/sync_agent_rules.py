"""Generate every AI assistant's rules file from the core rules in AGENTS.md.

AGENTS.md is the single source of truth. Its "Core rules (summary)" block (between the
`<!-- core-rules:start -->` and `<!-- core-rules:end -->` markers) is written into each tool's native
rules file, with that tool's required front matter, plus a pointer back to AGENTS.md.

    uv run python scripts/sync_agent_rules.py          # write / update all files (make rules)
    uv run python scripts/sync_agent_rules.py --check  # exit 1 if any file is missing or stale (used by tests)

Hand-written, not generated: AGENTS.md itself, CLAUDE.md (imports AGENTS.md), and the scoped Cursor rules
.cursor/rules/python-style.mdc and .cursor/rules/models-and-changelog.mdc.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AGENTS = ROOT / "AGENTS.md"
START, END = "<!-- core-rules:start -->", "<!-- core-rules:end -->"
NOTICE = ("<!-- Generated from AGENTS.md by scripts/sync_agent_rules.py. Do not edit this file: "
          "edit AGENTS.md, then run `make rules`. -->")


@dataclass(frozen=True)
class Target:
    path: str
    tool: str
    front_matter: str = ""


TARGETS = [
    Target(".cursor/rules/project.mdc", "Cursor",
           "---\ndescription: Project rules for the contract clause classifier (applies to every request)\n"
           "globs:\nalwaysApply: true\n---\n"),
    Target(".github/copilot-instructions.md", "GitHub Copilot"),
    Target("GEMINI.md", "Gemini CLI / Gemini Code Assist"),
    Target(".windsurf/rules/project.md", "Windsurf", "---\ntrigger: always_on\n---\n"),
    Target(".clinerules/project.md", "Cline"),
    Target(".roo/rules/project.md", "Roo Code"),
    Target(".continue/rules/project.md", "Continue", "---\nname: Project rules\nalwaysApply: true\n---\n"),
    Target(".amazonq/rules/project.md", "Amazon Q Developer"),
    Target(".junie/guidelines.md", "JetBrains Junie"),
    Target(".rules", "Zed"),
    Target("CONVENTIONS.md", "Aider"),
]

AIDER_CONF = ".aider.conf.yml"
AIDER_CONF_TEXT = (
    "# Generated by scripts/sync_agent_rules.py. Aider loads the project rules read-only on start.\n"
    "read:\n  - CONVENTIONS.md\n  - AGENTS.md\n  - MEMORY.md\n"
)


def core_rules(text: str) -> str:
    m = re.search(re.escape(START) + r"\n(.*?)\n" + re.escape(END), text, re.DOTALL)
    if not m:
        raise SystemExit(f"Core rules markers not found in {AGENTS}")
    return m.group(1).strip()


def render(target: Target, rules: str) -> str:
    body = (
        f"{NOTICE}\n\n"
        f"# Project rules: contract-clause-classifier ({target.tool})\n\n"
        "A contract clause-type classifier: Qwen3-0.6B fine-tuned on LEDGAR (72 clause types), versioned models,\n"
        "served through an OpenAI-compatible FastAPI with a browser playground.\n\n"
        "Full rules with reasons: `AGENTS.md` (sections: Rules, Model rules, Changelog rules, Security and privacy,\n"
        "Git, Data, Documentation, Style, Gotchas). Decisions and measurements: `MEMORY.md`.\n\n"
        f"{rules}\n"
    )
    return target.front_matter + body


def expected_files() -> dict[str, str]:
    rules = core_rules(AGENTS.read_text())
    files = {t.path: render(t, rules) for t in TARGETS}
    files[AIDER_CONF] = AIDER_CONF_TEXT
    return files


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for rel, content in expected_files().items():
        path = ROOT / rel
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {rel}")
    if check and stale:
        print("Out of sync with AGENTS.md (run `make rules`): " + ", ".join(stale))
        return 1
    if check:
        print(f"All {len(TARGETS) + 1} assistant rule files are in sync with AGENTS.md.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
