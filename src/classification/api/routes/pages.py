"""Model pages: GET /models/{compare,transformer,classical} (also with .html), their assets, and /changelog.html.

The pages are static files generated by `scripts/10_model_pages.py` (`make model-pages`) into docs/models/.
"""

from __future__ import annotations

from pathlib import Path

from fastapi import APIRouter, Request
from fastapi.responses import FileResponse, HTMLResponse

from ...config import resolve_path
from ..errors import APIError

router = APIRouter(tags=["pages"])
PAGES = ("compare", "transformer", "classical")


def _dir(request: Request) -> Path:
    return resolve_path(request.app.state.settings.pages_dir)


@router.get("/models", include_in_schema=False)
def models_index(request: Request):
    return model_page("compare", request)


@router.get("/models/{name}", response_class=HTMLResponse, summary="Model pages (compare, transformer, classical)")
def model_page(name: str, request: Request):
    """Generated model detail and comparison pages."""
    page = name[:-5] if name.endswith(".html") else name
    if page not in PAGES:
        raise APIError(404, f"No page '{name}'. Pages: {', '.join(PAGES)}", None, "not_found")
    path = _dir(request) / f"{page}.html"
    if not path.exists():
        raise APIError(404, f"{page}.html has not been generated yet. Run `make model-pages` (needs trained models).",
                       None, "not_generated")
    return HTMLResponse(path.read_text(encoding="utf-8"))


@router.get("/models/assets/{filename}", include_in_schema=False)
def model_asset(filename: str, request: Request):
    base = (_dir(request) / "assets").resolve()
    path = (base / filename).resolve()
    if base not in path.parents or not path.is_file():
        raise APIError(404, "Asset not found", None, "not_found")
    return FileResponse(path)


@router.get("/changelog.html", include_in_schema=False)
def changelog(request: Request):
    path = _dir(request).parent.parent / "changelog.html"
    if not path.exists():
        raise APIError(404, "changelog.html not found", None, "not_found")
    return HTMLResponse(path.read_text(encoding="utf-8"))
